#!/usr/bin/env python3
"""Check the jar tools.build just wrote.

The pom is generated by build.clj. This confirms the coordinates Clojars
shows, the homepage, the MIT licence, and the SCM URL.
"""

from __future__ import annotations

import sys
import xml.etree.ElementTree as ET
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JAR = ROOT / "target" / "coworkingview-0.1.0.jar"
POM = "META-INF/maven/net.clojars.coworkingview/coworkingview/pom.xml"
NS = {"m": "http://maven.apache.org/POM/4.0.0"}


def text_of(parent: ET.Element, path: str) -> str:
    found = parent.findall(path, NS)
    if len(found) != 1 or not (found[0].text and found[0].text.strip()):
        raise SystemExit(f"{path}: expected one element, found {len(found)}")
    return found[0].text.strip()


def main() -> int:
    if not JAR.is_file():
        print(f"missing {JAR}", file=sys.stderr)
        return 1
    with zipfile.ZipFile(JAR) as archive:
        names = set(archive.namelist())
        for required in (
            POM,
            "coworkingview/core.clj",
            "coworkingview/client.clj",
            "coworkingview/price-index.edn",
        ):
            if required not in names:
                print(f"jar is missing {required}", file=sys.stderr)
                return 1
        root = ET.fromstring(archive.read(POM))
    checks = {
        "./m:groupId": "net.clojars.coworkingview",
        "./m:artifactId": "coworkingview",
        "./m:version": "0.1.0",
        "./m:url": "https://coworkingview.com/en/tools/price-index",
        "./m:licenses/m:license/m:name": "MIT License",
        "./m:licenses/m:license/m:url": "https://opensource.org/licenses/MIT",
        "./m:scm/m:url": "https://github.com/coworkingview/flex-office-data",
        "./m:developers/m:developer/m:name": "CoworkingView",
        "./m:developers/m:developer/m:email": "info@coworkingview.com",
        "./m:developers/m:developer/m:organization": "CoworkingView",
        "./m:organization/m:name": "CoworkingView",
        "./m:organization/m:url": "https://coworkingview.com",
    }
    for path, expected in checks.items():
        actual = text_of(root, path)
        if actual != expected:
            print(f"{path}: {actual!r} != {expected!r}", file=sys.stderr)
            return 1
    description = text_of(root, "./m:description")
    if "Price Index" not in description or "CoworkingView" not in description:
        print(f"description does not name the Price Index: {description!r}", file=sys.stderr)
        return 1
    connection = text_of(root, "./m:scm/m:connection")
    if "github.com/coworkingview/flex-office-data" not in connection:
        print(f"scm connection does not point at the repository: {connection!r}", file=sys.stderr)
        return 1
    print(f"{JAR.name}: pom coordinates and homepage match")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
